"""
n8n AI Agent Node — Python implementation (provider-agnostic)

Mirrors the n8n AI Agent node:
  - Pluggable AI backend  (OpenAI, Anthropic, Ollama, or any custom provider)
  - API key + per-provider settings stored in one place
  - Tool registration with JSON-schema descriptions (function calling)
  - Swappable memory strategies (none, window buffer, summary)
  - A single .run(prompt) entry point that returns the final text response

Install extras as needed:
  pip install openai            # OpenAI / Azure / Ollama-compatible
  pip install anthropic         # Anthropic Claude
"""

from __future__ import annotations

import json
from abc import ABC, abstractmethod
from copy import deepcopy
from dataclasses import dataclass, field
from typing import Any, Callable


# ---------------------------------------------------------------------------
# Tool
# ---------------------------------------------------------------------------

@dataclass
class Tool:
    """
    A callable tool the agent may invoke.

    Parameters
    ----------
    name:
        Unique identifier used in function-calling payloads.
    description:
        Natural-language description sent to the model.
    parameters:
        JSON-Schema object describing the tool's input arguments.
    fn:
        Python callable that executes the tool and returns a string result.

    Example
    -------
    >>> import datetime
    >>> Tool(
    ...     name="get_date",
    ...     description="Returns today's date.",
    ...     parameters={"type": "object", "properties": {}, "required": []},
    ...     fn=lambda **_: str(datetime.date.today()),
    ... )
    """
    name: str
    description: str
    parameters: dict  # JSON Schema
    fn: Callable[..., str]

    def call(self, arguments: dict) -> str:
        """Execute the tool and return a string result."""
        try:
            result = self.fn(**arguments)
            return str(result)
        except Exception as exc:
            return f"Tool error: {exc}"


# ---------------------------------------------------------------------------
# Memory strategies
# ---------------------------------------------------------------------------

@dataclass
class Message:
    role: str   # "system" | "user" | "assistant" | "tool"
    content: str
    tool_call_id: str | None = None   # for tool-result messages


class BaseMemory(ABC):
    """Abstract memory — stores and retrieves the conversation history."""

    @abstractmethod
    def add(self, message: Message) -> None: ...

    @abstractmethod
    def get(self) -> list[Message]: ...

    @abstractmethod
    def clear(self) -> None: ...


class NoMemory(BaseMemory):
    """Stateless — each run starts fresh (only the current prompt is sent)."""

    def __init__(self) -> None:
        self._pending: list[Message] = []

    def add(self, message: Message) -> None:
        self._pending.append(message)

    def get(self) -> list[Message]:
        msgs = list(self._pending)
        self._pending.clear()
        return msgs

    def clear(self) -> None:
        self._pending.clear()


class WindowBufferMemory(BaseMemory):
    """
    Keeps the last *k* user/assistant turn-pairs.

    Equivalent to n8n's Window Buffer Memory sub-node.
    """

    def __init__(self, window_size: int = 10) -> None:
        self.window_size = window_size
        self._history: list[Message] = []

    def add(self, message: Message) -> None:
        self._history.append(message)
        # Trim to window_size turn-pairs (each pair = 2 messages)
        max_msgs = self.window_size * 2
        if len(self._history) > max_msgs:
            self._history = self._history[-max_msgs:]

    def get(self) -> list[Message]:
        return list(self._history)

    def clear(self) -> None:
        self._history.clear()


class SummaryMemory(BaseMemory):
    """
    Compresses old turns into a rolling summary kept as a system message.

    Equivalent to n8n's Summary Memory sub-node.
    The summary is regenerated by the backend whenever the buffer overflows.
    """

    def __init__(self, max_turns: int = 6) -> None:
        self.max_turns = max_turns
        self._summary: str = ""
        self._recent: list[Message] = []

    # The backend calls this to update the summary when needed
    def set_summary(self, summary: str) -> None:
        self._summary = summary
        self._recent.clear()

    def needs_summarization(self) -> bool:
        return len(self._recent) >= self.max_turns * 2

    def add(self, message: Message) -> None:
        self._recent.append(message)

    def get(self) -> list[Message]:
        msgs: list[Message] = []
        if self._summary:
            msgs.append(Message(role="system", content=f"Conversation so far:\n{self._summary}"))
        msgs.extend(self._recent)
        return msgs

    def clear(self) -> None:
        self._summary = ""
        self._recent.clear()


# ---------------------------------------------------------------------------
# AI Backend (provider abstraction)
# ---------------------------------------------------------------------------

@dataclass
class AISettings:
    """
    Provider-agnostic model settings.

    Any key not consumed by the backend is forwarded verbatim to the API,
    so provider-specific options (e.g. ``top_k``, ``seed``) can be passed
    without modifying this class.
    """
    model: str = "gpt-4o"
    temperature: float = 0.7
    max_tokens: int = 1024
    system_prompt: str = "You are a helpful assistant."
    extra: dict = field(default_factory=dict)


class AIBackend(ABC):
    """
    Abstract AI provider backend.

    Implement this class to add support for any AI provider.
    """

    def __init__(self, api_key: str, settings: AISettings) -> None:
        self.api_key = api_key
        self.settings = settings

    @abstractmethod
    def chat(
        self,
        messages: list[Message],
        tools: list[Tool],
    ) -> tuple[str | None, list[dict] | None]:
        """
        Send messages to the model.

        Returns
        -------
        (text_response, tool_calls)
            Exactly one of the two will be non-None on each call:
            - text_response: the model's final text reply
            - tool_calls: list of {"id": str, "name": str, "arguments": dict}
        """
        ...

    @property
    def provider_name(self) -> str:
        return self.__class__.__name__


