# Concrete backends
# ---------------------------------------------------------------------------

class OpenAIBackend(AIBackend):
    """
    Backend for OpenAI (and OpenAI-compatible APIs: Azure, Ollama, LM Studio …).

    Extra settings
    --------------
    base_url : str
        Override the API base URL (e.g. "http://localhost:11434/v1" for Ollama).
    """

    def __init__(self, api_key: str, settings: AISettings) -> None:
        super().__init__(api_key, settings)
        self._client = None  # lazily initialised on first chat() call

    def _get_client(self):
        if self._client is None:
            try:
                from openai import OpenAI
            except ImportError:
                raise ImportError("pip install openai")
            base_url = self.settings.extra.get("base_url")
            self._client = OpenAI(api_key=self.api_key, base_url=base_url)
        return self._client

    def chat(
        self,
        messages: list[Message],
        tools: list[Tool],
    ) -> tuple[str | None, list[dict] | None]:
        oai_msgs = self._to_oai_messages(messages)
        kwargs: dict[str, Any] = dict(
            model=self.settings.model,
            messages=oai_msgs,
            temperature=self.settings.temperature,
            max_tokens=self.settings.max_tokens,
            **{k: v for k, v in self.settings.extra.items() if k != "base_url"},
        )
        if tools:
            kwargs["tools"] = [self._tool_schema(t) for t in tools]
            kwargs["tool_choice"] = "auto"

        response = self._get_client().chat.completions.create(**kwargs)
        choice = response.choices[0]

        if choice.finish_reason == "tool_calls":
            calls = [
                {
                    "id": tc.id,
                    "name": tc.function.name,
                    "arguments": json.loads(tc.function.arguments),
                }
                for tc in choice.message.tool_calls
            ]
            return None, calls

        return choice.message.content, None

    @staticmethod
    def _to_oai_messages(messages: list[Message]) -> list[dict]:
        out = []
        for m in messages:
            if m.role == "tool":
                out.append({"role": "tool", "tool_call_id": m.tool_call_id, "content": m.content})
            else:
                out.append({"role": m.role, "content": m.content})
        return out

    @staticmethod
    def _tool_schema(tool: Tool) -> dict:
        return {
            "type": "function",
            "function": {
                "name": tool.name,
                "description": tool.description,
                "parameters": tool.parameters,
            },
        }


class AnthropicBackend(AIBackend):
    """
    Backend for Anthropic Claude models.

    Uses Anthropic's tool-use API for function calling.
    """

    def __init__(self, api_key: str, settings: AISettings) -> None:
        super().__init__(api_key, settings)
        self._client = None  # lazily initialised

    def _get_client(self):
        if self._client is None:
            try:
                import anthropic as _anthropic
            except ImportError:
                raise ImportError("pip install anthropic")
            self._client = _anthropic.Anthropic(api_key=self.api_key)
        return self._client

    def chat(
        self,
        messages: list[Message],
        tools: list[Tool],
    ) -> tuple[str | None, list[dict] | None]:
        # Anthropic separates system prompt from the messages array
        system = self.settings.system_prompt
        ant_msgs = [
            {"role": m.role if m.role != "tool" else "user", "content": m.content}
            for m in messages
            if m.role not in ("system",)
        ]

        kwargs: dict[str, Any] = dict(
            model=self.settings.model,
            max_tokens=self.settings.max_tokens,
            system=system,
            messages=ant_msgs,
            **{k: v for k, v in self.settings.extra.items()},
        )
        if tools:
            kwargs["tools"] = [
                {
                    "name": t.name,
                    "description": t.description,
                    "input_schema": t.parameters,
                }
                for t in tools
            ]

        response = self._get_client().messages.create(**kwargs)

        tool_uses = [b for b in response.content if b.type == "tool_use"]
        if tool_uses:
            calls = [
                {"id": b.id, "name": b.name, "arguments": b.input}
                for b in tool_uses
            ]
            return None, calls

        text_blocks = [b for b in response.content if b.type == "text"]
        return text_blocks[0].text if text_blocks else "", None


class OllamaBackend(OpenAIBackend):
    """
    Backend for local Ollama models (uses the OpenAI-compatible endpoint).

    Defaults to http://localhost:11434/v1 with no API key required.
    """

    def __init__(self, api_key: str = "ollama", settings: AISettings | None = None) -> None:
        if settings is None:
            settings = AISettings(model="llama3")
        settings.extra.setdefault("base_url", "http://localhost:11434/v1")
        super().__init__(api_key, settings)


# ---------------------------------------------------------------------------
# Registry — map provider name → backend class
# ---------------------------------------------------------------------------

_BACKEND_REGISTRY: dict[str, type[AIBackend]] = {
    "openai": OpenAIBackend,
    "anthropic": AnthropicBackend,
    "ollama": OllamaBackend,
}


def register_backend(name: str, cls: type[AIBackend]) -> None:
    """Register a custom backend so it can be referenced by name."""
    _BACKEND_REGISTRY[name.lower()] = cls


# ---------------------------------------------------------------------------
# AI Agent Node
# ---------------------------------------------------------------------------

class AIAgentNode:
    """
    Provider-agnostic AI Agent node.

    Mirrors n8n's AI Agent node: a model backend + tools + memory wired
    together into a single .run(prompt) call.

    Parameters
    ----------
    provider:
        One of "openai", "anthropic", "ollama", or a name registered via
        register_backend().
    api_key:
        API key for the chosen provider.
    settings:
        AISettings instance controlling model, temperature, system prompt, etc.
    memory:
        A BaseMemory instance. Defaults to WindowBufferMemory(window_size=10).
    max_iterations:
        Guard against infinite tool-call loops (default 10).

    Example
    -------
    >>> agent = AIAgentNode(
    ...     provider="openai",
    ...     api_key="sk-...",
    ...     settings=AISettings(model="gpt-4o", temperature=0.3),
    ... )
    >>> agent.add_tool(my_tool)
    >>> print(agent.run("What's 2 + 2?"))
    """

    def __init__(
        self,
        provider: str,
        api_key: str,
        settings: AISettings | None = None,
        memory: BaseMemory | None = None,
        max_iterations: int = 10,
    ) -> None:
        self.settings = settings or AISettings()
        self.memory = memory or WindowBufferMemory()
        self.max_iterations = max_iterations
        self._tools: dict[str, Tool] = {}

        backend_cls = _BACKEND_REGISTRY.get(provider.lower())
        if backend_cls is None:
            raise ValueError(
                f"Unknown provider '{provider}'. "
                f"Available: {list(_BACKEND_REGISTRY)}. "
                "Use register_backend() to add a custom provider."
            )
        self.backend: AIBackend = backend_cls(api_key, self.settings)

    # ------------------------------------------------------------------
    # Tool management
    # ------------------------------------------------------------------

    def add_tool(self, tool: Tool) -> None:
        """Register a tool the agent can call."""
        self._tools[tool.name] = tool

    def remove_tool(self, name: str) -> None:
        """Unregister a tool by name."""
        self._tools.pop(name, None)

    @property
    def tools(self) -> list[Tool]:
        return list(self._tools.values())

    # ------------------------------------------------------------------
    # Memory management
    # ------------------------------------------------------------------

    def set_memory(self, memory: BaseMemory) -> None:
        """Swap the memory strategy at runtime."""
        self.memory = memory

    def clear_memory(self) -> None:
        """Reset conversation history."""
        self.memory.clear()

    # ------------------------------------------------------------------
    # Core run loop (ReAct-style: think → act → observe → repeat)
    # ------------------------------------------------------------------

    def run(self, prompt: str) -> str:
        """
        Process a user prompt and return the agent's final text response.

        The agent will call tools as needed (up to max_iterations) before
        returning its final answer.
        """
        # Build the full message list: system + history + new user message
        system_msg = Message(role="system", content=self.settings.system_prompt)
        user_msg = Message(role="user", content=prompt)

        self.memory.add(user_msg)

        for _ in range(self.max_iterations):
            messages = [system_msg] + self.memory.get()

            text, tool_calls = self.backend.chat(messages, self.tools)

            # Model returned a final text answer
            if text is not None:
                assistant_msg = Message(role="assistant", content=text)
                self.memory.add(assistant_msg)

                # SummaryMemory: compress if the buffer is full
                if (
                    isinstance(self.memory, SummaryMemory)
                    and self.memory.needs_summarization()
                ):
                    summary_prompt = (
                        "Summarize the conversation so far in a few sentences, "
                        "preserving key facts and decisions."
                    )
                    summary, _ = self.backend.chat(
                        [system_msg] + self.memory.get() + [Message(role="user", content=summary_prompt)],
                        [],
                    )
                    self.memory.set_summary(summary or "")

                return text

            # Model wants to call one or more tools
            for call in (tool_calls or []):
                tool = self._tools.get(call["name"])
                result = tool.call(call["arguments"]) if tool else f"Unknown tool: {call['name']}"

                # Record tool invocation + result in memory
                self.memory.add(
                    Message(role="assistant", content=f"[tool_call:{call['name']}] {json.dumps(call['arguments'])}")
                )
                self.memory.add(
                    Message(role="tool", content=result, tool_call_id=call.get("id"))
                )

        return "Max iterations reached without a final answer."

    # ------------------------------------------------------------------
    # Info
    # ------------------------------------------------------------------

    def __repr__(self) -> str:
        return (
            f"AIAgentNode(provider={self.backend.provider_name}, "
            f"model={self.settings.model}, "
            f"tools={list(self._tools)}, "
            f"memory={type(self.memory).__name__})"
        )


